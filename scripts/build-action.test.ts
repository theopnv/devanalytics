import { describe, expect, test } from 'vitest';
import type { CollectorEntry } from '../core/contract.ts';
import { renderMetricInputs, replaceMetricInputs } from './build-action.mts';

const entry = (name: string, inputs: { name: string; description: string; default?: string }[]): CollectorEntry => ({
  metric: { name, key: 'commit', parse: (body) => body as never },
  collector: { inputs, collect: async () => ({ sha: '', date: '' }) },
});

describe('renderMetricInputs', () => {
  test('writes one optional input with the metric name and the default in its description', () => {
    expect(renderMetricInputs([entry('complexity', [{ name: 'include', description: 'Files to read.', default: 'src/**' }])])).toBe(
      '  include:\n    description: "complexity: Files to read. Default: src/**."\n    required: false\n',
    );
  });

  test('writes an input that two metrics share once, with both descriptions', () => {
    const text = renderMetricInputs([
      entry('coverage', [{ name: 'reports', description: 'Coverage reports.' }]),
      entry('tests', [{ name: 'reports', description: 'Test reports.', default: 'a=b' }]),
    ]);

    expect(text.match(/reports:/g)).toHaveLength(1);
    expect(text).toContain('"coverage: Coverage reports. tests: Test reports. Default: a=b."');
  });

  test('refuses an input that has the name of a core input', () => {
    expect(() => renderMetricInputs([entry('bad', [{ name: 'token', description: '' }])])).toThrow('already an input of the Action');
  });

  test('writes nothing when no metric has an input', () => {
    expect(renderMetricInputs([entry('plain', [])])).toBe('');
  });
});

describe('replaceMetricInputs', () => {
  const yml = 'inputs:\n  # BEGIN METRIC INPUTS (generated by `npm run build:action`)\n  old:\n    required: false\n  # END METRIC INPUTS\nruns:\n';

  test('replaces what is between the markers and keeps the rest', () => {
    expect(replaceMetricInputs(yml, '  new:\n    required: false\n')).toBe(
      'inputs:\n  # BEGIN METRIC INPUTS (generated by `npm run build:action`)\n  new:\n    required: false\n  # END METRIC INPUTS\nruns:\n',
    );
  });

  test('gives the same text when it runs twice', () => {
    const once = replaceMetricInputs(yml, '  new:\n');

    expect(replaceMetricInputs(once, '  new:\n')).toBe(once);
  });

  test('refuses a file without the markers', () => {
    expect(() => replaceMetricInputs('inputs:\n', '')).toThrow('markers');
  });
});
